/* =====================================================================
   SmartMart  |  09_concurrency_lock_demo.sql
   การทับซ้อนของงาน (Concurrency Control) : ตอนแอดมินกำลังแก้ไขคูปอง (โปรโมชัน)
   ลูกค้าต้องอ่าน/ใช้ส่วนลดนั้นไม่ได้ จนกว่าแอดมินจะอัปเดตเสร็จ (commit) ก่อน

   ต้องเปิด SSMS 2 แท็บ (จำลอง 2 คนทำงานพร้อมกัน) รันตามลำดับนี้ :
     แท็บ A (แอดมิน)  -> รัน STEP A1 ก่อน (จะค้างอยู่ ยังไม่ commit)
     แท็บ B (ลูกค้า)   -> รัน STEP B1 ขณะที่แท็บ A ยังค้างอยู่ -> จะ "หมุนรอ" ไม่ตอบกลับทันที
     แท็บ A (แอดมิน)  -> รัน STEP A2 (COMMIT) -> ทันทีที่ COMMIT แท็บ B จะได้ผลลัพธ์กลับมาทันที
                         (ไม่ใช่ค่ากลางๆ ระหว่างแก้ แต่เป็นค่าใหม่ที่ถูกต้องเสมอ)
   ===================================================================== */
USE SmartMart;
GO

/* ---------- เตรียมข้อมูลทดสอบ (รันครั้งเดียวในแท็บไหนก็ได้ก่อนเริ่ม) ---------- */
DELETE FROM dbo.sales_promotion WHERE UPC = '099000000005' AND promotion_start_date = '2027-06-01';
INSERT INTO dbo.sales_promotion (UPC, promotion_start_date, promotion_end_date, promotion_type_code, promotion_details, discount_percent)
VALUES ('099000000005', '2027-06-01', '2027-06-30', 1, 'Early Summer Sale', 15.00);
GO

/* =====================================================================
   STEP A1 (แท็บ A, สวมสิทธิ์แอดมิน pm1) : เริ่มแก้ส่วนลดจาก 15% เป็น 30% แต่ "ยังไม่ COMMIT"
   รันบล็อกนี้แล้วแท็บจะค้างรอคำสั่งถัดไป (ปกติ) ห้ามปิดแท็บ ห้ามรัน GO
   ===================================================================== */
EXECUTE AS USER = 'pm1';
BEGIN TRAN;
    UPDATE dbo.sales_promotion
    SET discount_percent = 30.00, promotion_details = 'Flash Sale!'
    WHERE UPC = '099000000005' AND promotion_start_date = '2027-06-01';
    -- แถวนี้ถูกล็อกแบบ exclusive (X lock) แล้วตั้งแต่บรรทัดนี้ จนกว่าจะ COMMIT/ROLLBACK
    PRINT 'UPDATE แล้ว ยังไม่ commit -- ไปรัน STEP B1 ในอีกแท็บได้เลย';
-- *** ยังไม่ COMMIT ที่นี่ ให้ไปรัน STEP B1 ในแท็บ B ก่อน ***


/* =====================================================================
   STEP B1 (แท็บ B, สวมสิทธิ์ลูกค้าเว็บ login_app_webshop) : อ่านส่วนลดตอนเช็คเอาท์
   รันขณะที่แท็บ A ยัง BEGIN TRAN ค้างอยู่ (ยังไม่ COMMIT)
   ผลที่ต้องเห็น : แท็บนี้จะ "หมุนรอ" ไม่คืนผลลัพธ์ จนกว่าแท็บ A จะ COMMIT (STEP A2) เท่านั้น
   ===================================================================== */
EXECUTE AS USER = 'login_app_webshop';
SELECT discount_percent
FROM dbo.sales_promotion
WHERE UPC = '099000000005' AND promotion_start_date = '2027-06-01';
-- [BLOCKED] ค้างรอ (ไม่ตอบกลับ) จนกว่า STEP A2 จะ COMMIT -- นี่คือพฤติกรรมที่ถูกต้อง
REVERT;
GO


/* =====================================================================
   STEP A2 (กลับไปรันต่อในแท็บ A) : ยืนยันการแก้ไข
   พอรันบรรทัดนี้ปุ๊บ แท็บ B (STEP B1) จะได้ผลลัพธ์ discount_percent = 30.00 ทันที
   ===================================================================== */
    COMMIT TRAN;
REVERT;
GO


